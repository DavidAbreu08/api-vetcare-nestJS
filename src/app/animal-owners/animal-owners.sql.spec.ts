import { join } from "path";
import { DataSource, IsNull, MssqlParameter, SelectQueryBuilder } from "typeorm";
import { AnimalEntity } from "../animal/entities/animal.entity";
import { AnimalBusinessService } from "../animal/animal.business.service";
import { AnimalMeasurementEntity } from "../animal-measurements/entities/animal-measurement.entity";
import { MeasurementBusinessService } from "../animal-measurements/measurement.business.service";
import { ClinicalVisitBusinessService } from "../clinical-visits/clinical-visit.business.service";
import { ClinicalVisitEntity } from "../clinical-visits/entities/clinical-visit.entity";
import { Actor } from "../core/authorization";
import { PersistenceService } from "../core/persistence/persistence.service";
import { ReservationEntity } from "../reservation/entities/reservation.entity";
import { ReservationBusinessService } from "../reservation/reservation.business.service";
import { AnimalAccessService } from "./animal-access.service";
import { AnimalOwnerEntity } from "./entities/animal-owner.entity";
import { AnimalOwnerEndReason } from "./enums/animal-owner-end-reason.enum";

const client: Actor = { id: "U-1", roleIds: [], isAdmin: false, isEmployee: false, isClient: true, employeeId: null };
const TUTOR_EXISTS = (animalColumn: string, param: string) =>
  `EXISTS (SELECT 1 FROM vc_animal_owners ao_tutor WHERE ao_tutor.animal_id = ${animalColumn} AND ao_tutor.user_id = :${param} AND ao_tutor.ended_at IS NULL)`;

/**
 * Real TypeORM metadata (no database connection): the SQL generated for vc_animal_owners and for every read that now
 * filters by active tutors (EXISTS), so a relation mapping mistake (e.g. a property name instead of a column, or a
 * composite join sharing a column) fails here instead of in SQL Server.
 */
describe("Tutorship SQL generated by TypeORM metadata", () => {
  let ds: DataSource;
  const flat = (sql: string) => sql.replace(/\s+/g, " ");

  beforeAll(async () => {
    ds = new DataSource({ type: "mssql", entities: [join(__dirname, "../../**/*.entity{.ts,.js}")] });
    await (ds as unknown as { buildMetadatas(): Promise<void> }).buildMetadatas();
    // Loading every entity through ts-jest can exceed the default 5 s when the whole suite runs in parallel.
  }, 30_000);
  afterEach(() => jest.restoreAllMocks());

  /** Intercepts getMany, returning the SQL each query would execute. */
  function capture(): string[] {
    const queries: string[] = [];
    jest.spyOn(SelectQueryBuilder.prototype, "getMany").mockImplementation(function (this: SelectQueryBuilder<any>) {
      queries.push(flat(this.getQuery()));
      return Promise.resolve([]);
    });
    return queries;
  }

  it("declares the names of migration 1795435200000 (FKs, filtered indexes, checks, ix_vc_animals_owner_id)", () => {
    const owners = ds.getMetadata(AnimalOwnerEntity);
    expect(owners.tableName).toBe("vc_animal_owners");
    expect(owners.foreignKeys.map(fk => `${fk.name}:${fk.columnNames}`).sort()).toEqual([
      "fk_vc_animal_owners_animal:animal_id", "fk_vc_animal_owners_assigned_by:assigned_by", "fk_vc_animal_owners_ended_by:ended_by", "fk_vc_animal_owners_user:user_id",
    ]);
    const index = (name: string) => owners.indices.find(candidate => candidate.name === name);
    expect(index("uq_vc_animal_owners_active")).toMatchObject({ isUnique: true, where: "[ended_at] IS NULL" });
    expect(index("uq_vc_animal_owners_active")?.columns.map(column => column.databaseName)).toEqual(["animal_id", "user_id"]);
    expect(index("uq_vc_animal_owners_primary")).toMatchObject({ isUnique: true, where: "[ended_at] IS NULL AND [is_primary] = 1" });
    expect(index("uq_vc_animal_owners_primary")?.columns.map(column => column.databaseName)).toEqual(["animal_id"]);
    expect(index("ix_vc_animal_owners_user_active")).toMatchObject({ isUnique: false, where: "[ended_at] IS NULL" });
    expect(index("ix_vc_animal_owners_user_active")?.columns.map(column => column.databaseName)).toEqual(["user_id", "animal_id"]);
    expect(index("ix_vc_animal_owners_animal_assigned")?.columns.map(column => column.databaseName)).toEqual(["animal_id", "assigned_at"]);
    expect(owners.indices.map(candidate => candidate.name).sort()).toEqual([
      "ix_vc_animal_owners_animal_assigned", "ix_vc_animal_owners_assigned_by", "ix_vc_animal_owners_ended_by", "ix_vc_animal_owners_user_active",
      "uq_vc_animal_owners_active", "uq_vc_animal_owners_primary",
    ]);
    expect(owners.checks.map(check => check.name).sort()).toEqual(["ck_vc_animal_owners_dates", "ck_vc_animal_owners_end_reason", "ck_vc_animal_owners_ended"]);
    expect(owners.checks.find(check => check.name === "ck_vc_animal_owners_end_reason")?.expression)
      .toContain("N'TRANSFERRED', N'REMOVED', N'ROLE_CHANGED', N'ACCOUNT_DELETED', N'MIGRATED'");
    const ownerIndex = ds.getMetadata(AnimalEntity).indices.find(candidate => candidate.name === "ix_vc_animals_owner_id");
    expect(ownerIndex?.columns.map(column => column.databaseName)).toEqual(["owner_id"]);
  });

  it("writes each vc_animal_owners column once by its physical name in INSERT and UPDATE (close)", () => {
    const [insert, insertParams] = ds.createQueryBuilder().insert().into(AnimalOwnerEntity).values({
      animalId: "A-1", userId: "U-1", isPrimary: true, assignedAt: new Date("2030-01-01T10:00:00Z"), endedAt: null, assignedBy: "ADM", endedBy: null, endReason: null,
    }).getQueryAndParameters();
    const [, columnList] = /^INSERT INTO "vc_animal_owners"\((.*?)\) OUTPUT/.exec(flat(insert)) ?? /^INSERT INTO "vc_animal_owners"\((.*?)\) VALUES/.exec(flat(insert)) ?? [];
    const columns = columnList.split(", ").map(column => column.slice(1, -1));
    for (const column of ["animal_id", "user_id", "is_primary", "assigned_at", "ended_at", "assigned_by", "ended_by", "end_reason"]) {
      expect(columns.filter(name => name === column)).toHaveLength(1);
    }
    expect(columns.join(",")).not.toMatch(/[A-Z]/);
    expect(insertParams.map(param => param?.value ?? param)).toEqual(expect.arrayContaining(["A-1", "U-1", "ADM"]));

    const [update] = ds.createQueryBuilder().update(AnimalOwnerEntity)
      .set({ endedAt: new Date(), endedBy: "ADM", endReason: AnimalOwnerEndReason.TRANSFERRED }).where({ id: "O-1" }).getQueryAndParameters();
    const assigned = [...flat(update).split(" WHERE ")[0].matchAll(/"([a-zA-Z_]+)" = /g)].map(match => match[1]);
    expect(assigned).toEqual(expect.arrayContaining(["ended_at", "ended_by", "end_reason", "updated_at"]));
    expect(assigned.join(",")).not.toMatch(/endedAt|endedBy|endReason/);
  });

  it("synchronizes vc_animals.owner_id through the owner relation (transfer)", () => {
    const [update] = ds.createQueryBuilder().update(AnimalEntity).set({ owner: { id: "U-2" } }).where({ id: "A-1" }).getQueryAndParameters();
    expect(flat(update)).toMatch(/^UPDATE "vc_animals" SET "owner_id" = @0, "updated_at" = .* WHERE "id" = @1$/);
  });

  it("reads active tutors by mapped columns, joining the account by user_id", () => {
    const sql = flat(ds.getRepository(AnimalOwnerEntity).createQueryBuilder("AnimalOwnerEntity").setFindOptions({
      where: { animalId: "A-1", endedAt: IsNull() }, relations: { user: true }, order: { isPrimary: "DESC", assignedAt: "ASC" },
    }).getQuery());
    expect(sql).toContain(`LEFT JOIN "vc_users" "AnimalOwnerEntity__AnimalOwnerEntity_user" ON "AnimalOwnerEntity__AnimalOwnerEntity_user"."id"="AnimalOwnerEntity"."user_id"`);
    expect(sql).toContain(`"AnimalOwnerEntity"."animal_id" = :orm_param_0`);
    expect(sql).toContain(`"AnimalOwnerEntity"."ended_at" IS NULL`);
    expect(sql).not.toMatch(/animalId|endedAt"/);
  });

  it("lists primary tutorships of non-deleted animals by user (account deletion / role change)", async () => {
    const queries = capture();
    await new AnimalAccessService({} as any, new PersistenceService()).primaryAnimalIdsOf(ds.manager, "U-1");
    expect(queries[0]).toContain(`FROM "vc_animal_owners" "o" INNER JOIN "vc_animals" "animal" ON "animal"."id"="o"."animal_id" AND ("animal"."deleted_at" IS NULL)`);
    expect(queries[0]).toContain(`WHERE "o"."user_id" = :userId AND "o"."is_primary" = 1 AND "o"."ended_at" IS NULL`);
  });

  it("closes secondary tutorships with typed parameters and never before assigned_at", async () => {
    const query = jest.fn(async () => [{ animal_id: "A-1" }]);
    const now = new Date("2030-01-01T10:00:00.123Z");
    const ids = await new AnimalAccessService({} as any, new PersistenceService())
      .closeSecondaryTutorships({ query } as any, "U-1", AnimalOwnerEndReason.ACCOUNT_DELETED, "ADM", now);
    expect(ids).toEqual(["A-1"]);
    const [sql, params] = query.mock.calls[0] as unknown as [string, MssqlParameter[]];
    expect(sql).toBe("UPDATE [dbo].[vc_animal_owners] SET [ended_at] = CASE WHEN [assigned_at] > @0 THEN [assigned_at] ELSE @0 END, "
      + "[ended_by] = @1, [end_reason] = @2, [updated_at] = SYSDATETIME() OUTPUT inserted.[animal_id] "
      + "WHERE [user_id] = @3 AND [is_primary] = 0 AND [ended_at] IS NULL");
    expect(params.map(param => [param.type, param.value instanceof Date ? "date" : param.value])).toEqual([
      ["datetime2", "date"], ["uniqueidentifier", "ADM"], ["nvarchar", "ACCOUNT_DELETED"], ["uniqueidentifier", "U-1"],
    ]);
  });

  it("filters animals by active tutor (getAll, findByOwner) with joins by mapped columns", async () => {
    const queries = capture();
    const measurements = { latestMany: async () => new Map() };
    const access = { activeTutorsOf: async () => new Map() };
    const business = new AnimalBusinessService(ds.getRepository(AnimalEntity), {} as any, {} as any, {} as any, new PersistenceService(),
      measurements as any, {} as any, {} as any, {} as any, access as any, {} as any);
    await business.getAll({ skip: 0, take: 10, speciesId: "S-1" } as any, client);
    const sql = queries[0];
    expect(sql).toContain(`LEFT JOIN "vc_users" "owner" ON "owner"."id"="animal"."owner_id"`);
    expect(sql).toContain(`LEFT JOIN "vc_species" "species" ON "species"."id"="animal"."species_id"`);
    expect(sql).toContain(`LEFT JOIN "vc_breeds" "breed" ON "breed"."id"="animal"."breed_id"`);
    expect(sql).toContain(TUTOR_EXISTS(`"animal"."id"`, "tutorId"));
    expect(sql).toContain(`"animal"."species_id" = :speciesId`);
    expect(sql).not.toMatch(/"animal"\."(speciesId|ownerId)"|animalId/);
  });

  it("filters measurements of a client by active tutor of measurement.animal_id", async () => {
    const queries = capture();
    const service = new MeasurementBusinessService(ds.getRepository(AnimalMeasurementEntity), {} as any, new PersistenceService(), {} as any, {} as any, {} as any);
    await service.list({ skip: 0, take: 10 } as any, client);
    expect(queries[0]).toContain(TUTOR_EXISTS(`"measurement"."animal_id"`, "tutorId"));
    expect(queries[0]).not.toContain(`"owner"`);
  });

  it("scopes clinical visits of a client to animals they are an active tutor of", async () => {
    const queries = capture();
    const service = new ClinicalVisitBusinessService(new PersistenceService(), {} as any, {} as any, ds.getRepository(ClinicalVisitEntity), ds.getRepository(ReservationEntity), {} as any);
    await service.list({ skip: 0, take: 10 } as any, client);
    expect(queries[0]).toContain(`WHERE (${TUTOR_EXISTS(`"visit"."animal_id"`, "actorId")})`);
    expect(queries[0]).toContain(`LEFT JOIN "vc_users" "owner" ON "owner"."id"="animal"."owner_id"`);
    expect(queries[0]).not.toContain(`"owner"."id" = :actorId`);
  });

  it("lets every active tutor list the animal's reservations, besides the reservation's client", async () => {
    const queries = capture();
    const service = new ReservationBusinessService(new PersistenceService(), {} as any, {} as any, {} as any, {} as any, {} as any,
      ds.getRepository(ReservationEntity), {} as any, {} as any, {} as any);
    await service.list({ skip: 0, take: 10 } as any, client);
    expect(queries[0]).toContain(`("reservation"."client_id" = :actorId OR ${TUTOR_EXISTS(`"reservation"."animal_id"`, "actorId")})`);
  });
});
