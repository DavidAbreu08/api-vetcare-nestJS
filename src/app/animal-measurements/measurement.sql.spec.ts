import { join } from "path";
import { DataSource, SelectQueryBuilder } from "typeorm";
import { ClinicalVisitEntity } from "../clinical-visits/entities/clinical-visit.entity";
import { PersistenceService } from "../core/persistence/persistence.service";
import { AnimalMeasurementEntity } from "./entities/animal-measurement.entity";
import { MeasurementBusinessService } from "./measurement.business.service";
import { AnimalEntity } from "../animal/entities/animal.entity";
import { BreedEntity } from "../breeds/entities/breed.entity";
import { SpeciesEntity } from "../species/entities/species.entity";
import { EmployeeEntity } from "../employees/entities/employee.entity";
import { ReservationEntity } from "../reservation/entities/reservation.entity";
import { findOpenReservations } from "../reservation/open-reservations";

/**
 * Builds the real TypeORM metadata in memory (no database connection) and checks the SQL generated for the
 * relations used by the measurement reads. Guards against composite join columns sharing animal_id, which
 * TypeORM 0.3 maps by overwriting the shared column metadata (e.g. "animal"."animalId" = ...).
 */
describe("Measurement SQL generated by TypeORM metadata", () => {
  let ds: DataSource;
  const flat = (sql: string) => sql.replace(/\s+/g, " ");

  beforeAll(async () => {
    ds = new DataSource({ type: "mssql", entities: [join(__dirname, "../../**/*.entity{.ts,.js}")] });
    await (ds as unknown as { buildMetadatas(): Promise<void> }).buildMetadatas();
  });
  afterEach(() => jest.restoreAllMocks());

  /** Runs a service read with getMany intercepted, returning the SQL it would execute. */
  async function captured(run: (service: MeasurementBusinessService) => Promise<unknown>): Promise<string[]> {
    const queries: string[] = [];
    jest.spyOn(SelectQueryBuilder.prototype, "getMany").mockImplementation(function (this: SelectQueryBuilder<any>) {
      queries.push(flat(this.getQuery()));
      return Promise.resolve([]);
    });
    const service = new MeasurementBusinessService(ds.getRepository(AnimalMeasurementEntity), {} as any, new PersistenceService(), {} as any, {} as any);
    await run(service);
    return queries;
  }

  it("joins animal by id and the clinical visit by clinical_visit_id in the list query", async () => {
    const [sql] = await captured(service => service.list({ skip: 0, take: 10 } as any, { id: "admin", roleIds: [], isAdmin: true, isEmployee: false, isClient: false, employeeId: null }));
    expect(sql).toContain(`INNER JOIN "vc_animals" "animal" ON "animal"."id"="measurement"."animal_id"`);
    expect(sql).toContain(`LEFT JOIN "vc_clinical_visits" "clinicalVisit" ON "clinicalVisit"."id"="measurement"."clinical_visit_id"`);
    expect(sql).not.toMatch(/animalId"|"clinicalVisit"\."animal_id"="measurement"/);
  });

  it("joins the clinical visit by clinical_visit_id in the latest-values batch query", async () => {
    const [sql] = await captured(service => service.latestMany(["a1"]));
    const joins = sql.match(/LEFT JOIN "vc_clinical_visits" "clinicalVisit" ON [^ ]+/g) ?? [];
    expect(joins.length).toBe(2);
    for (const on of joins) expect(on).toContain(`"clinicalVisit"."id"="measurement"."clinical_visit_id"`);
  });

  it("joins a clinical visit's reservation by reservation_id and its animal by animal_id", () => {
    const sql = flat(ds.getRepository(ClinicalVisitEntity).createQueryBuilder("visit")
      .leftJoin("visit.reservation", "reservation").leftJoin("visit.animal", "animal").getQuery());
    expect(sql).toContain(`LEFT JOIN "vc_reservations" "reservation" ON "reservation"."id"="visit"."reservation_id"`);
    expect(sql).toContain(`LEFT JOIN "vc_animals" "animal" ON "animal"."id"="visit"."animal_id"`);
  });

  it("selects open reservations by the mapped column, open statuses and end_at, ordered by start (lifecycle checks)", async () => {
    const queries: string[] = [];
    jest.spyOn(SelectQueryBuilder.prototype, "getMany").mockImplementation(function (this: SelectQueryBuilder<any>) {
      queries.push(flat(this.getQuery()));
      return Promise.resolve([]);
    });
    for (const filter of [{ employeeId: "E-1" }, { clientId: "U-1" }, { animalId: "A-1" }]) await findOpenReservations(ds.manager, filter);
    expect(queries[0]).toContain(`FROM "vc_reservations" "r" WHERE "r"."employee_id" = :value AND "r"."status" IN (:...openStatuses) AND "r"."end_at" > :now`);
    expect(queries[1]).toContain(`WHERE "r"."client_id" = :value`);
    expect(queries[2]).toContain(`WHERE "r"."animal_id" = :value`);
    expect(queries[0]).toContain(`"r"."start_at" AS "r_start_at"`);
    expect(queries[0]).toContain(`ORDER BY "r_start_at" ASC, "r_id" ASC`);
    for (const sql of queries) expect(sql).not.toMatch(/JOIN|"r"\."(employeeId|clientId|animalId|endAt)"/);
  });

  it("joins an animal's species by species_id and its breed by breed_id only (no shared composite column)", () => {
    const sql = flat(ds.getRepository(AnimalEntity).createQueryBuilder("animal")
      .leftJoinAndSelect("animal.species", "species").leftJoinAndSelect("animal.breed", "breed").getQuery());
    expect(sql).toContain(`LEFT JOIN "vc_species" "species" ON "species"."id"="animal"."species_id"`);
    expect(sql).toContain(`LEFT JOIN "vc_breeds" "breed" ON "breed"."id"="animal"."breed_id"`);
    expect(sql).not.toMatch(/speciesId|"breed"\."species_id"="animal"/);
  });

  it("writes species_id and breed_id (single-column breed relation) in animal INSERT and UPDATE", () => {
    /** Value bound to each written column: the driver placeholder "@N" resolves to the N-th parameter, DEFAULT stays as is. */
    const bound = (columns: string[], tokens: string[], params: any[]) => {
      const written: Record<string, unknown[]> = {};
      columns.forEach((column, index) => {
        const param = /^@(\d+)$/.exec(tokens[index]);
        (written[column] ??= []).push(param ? params[Number(param[1])]?.value ?? params[Number(param[1])] : tokens[index]);
      });
      return written;
    };
    const animal = ds.getRepository(AnimalEntity).create({
      name: "Mia", color: "preto", sex: "F", isVerified: false, owner: { id: "U-1" } as any,
      speciesId: "S-1", species: { id: "S-1" } as any, breedId: "B-1", breed: { id: "B-1", speciesId: "S-1" } as any,
    });
    const [insert, insertParams] = ds.createQueryBuilder().insert().into(AnimalEntity).values(animal).getQueryAndParameters();
    const [, columnList, valueList] = /^INSERT INTO "vc_animals"\((.*)\) VALUES \((.*)\)/.exec(flat(insert)) ?? [];
    const inserted = bound(columnList.split(", ").map(column => column.slice(1, -1)), valueList.split(", "), insertParams);
    // Each column written exactly once (no duplicate breed_id/species_id from the relation), with its own id.
    expect(inserted).toMatchObject({ species_id: ["S-1"], breed_id: ["B-1"], owner_id: ["U-1"] });
    expect(Object.keys(inserted)).not.toEqual(expect.arrayContaining(["speciesId"]));
    expect(Object.keys(inserted)).not.toContain("breedId");

    const [update, updateParams] = ds.createQueryBuilder().update(AnimalEntity)
      .set({ speciesId: "S-2", species: { id: "S-2" } as any, breedId: "B-2", breed: { id: "B-2" } as any })
      .where("id = :id", { id: "CAT" }).getQueryAndParameters();
    const assignments = [...flat(update).split(" WHERE ")[0].matchAll(/"([a-zA-Z_]+)" = (@\d+|\w+)/g)];
    const updated = bound(assignments.map(match => match[1]), assignments.map(match => match[2]), updateParams);
    expect(updated).toMatchObject({ species_id: ["S-2"], breed_id: ["B-2"] });
    expect(Object.keys(updated)).not.toEqual(expect.arrayContaining(["speciesId"]));
    expect(Object.keys(updated)).not.toContain("breedId");
  });

  it("locks the employee profile without joining its account (requireBookableEmployee)", () => {
    const sql = flat(ds.getRepository(EmployeeEntity).createQueryBuilder("employee")
      .where("employee.id = :id", { id: "E-1" }).setLock("pessimistic_write").getQuery());
    expect(sql).toContain(`FROM "vc_employees" "employee" WITH (UPDLOCK, ROWLOCK) WHERE "employee"."id" = :id`);
    expect(sql).not.toContain("JOIN");
  });

  it("declares the constraint and index names of the migrations", () => {
    const visit = ds.getMetadata(ClinicalVisitEntity);
    const inProgress = visit.indices.find(index => index.name === "uq_vc_clinical_visits_animal_in_progress");
    expect(inProgress).toMatchObject({ isUnique: true, where: "[status] = N'IN_PROGRESS'" });
    expect(inProgress?.columns.map(column => column.databaseName)).toEqual(["animal_id"]);
    expect(visit.indices.map(index => index.name)).toContain("ix_vc_clinical_visits_completed_by");
    expect(visit.checks.map(check => check.name)).toContain("ck_vc_clinical_visits_voided_dates");
    expect(visit.foreignKeys.map(fk => fk.name).sort()).toEqual([
      "fk_vc_clinical_visits_animal", "fk_vc_clinical_visits_completed_by", "fk_vc_clinical_visits_employee", "fk_vc_clinical_visits_voided_by",
    ]);
    const animal = ds.getMetadata(AnimalEntity);
    expect(animal.foreignKeys.map(fk => `${fk.name}:${fk.columnNames}`).sort()).toEqual(["fk_vc_animals_owner:owner_id", "fk_vc_animals_species:species_id"]);
    expect(animal.indices.map(index => index.name).sort()).toEqual(["ix_vc_animals_breed_species", "ix_vc_animals_species"]);
    expect(ds.getMetadata(BreedEntity).uniques.map(unique => unique.name).sort()).toEqual(["uq_vc_breeds_id_species", "uq_vc_breeds_species_name"]);
    expect(ds.getMetadata(BreedEntity).foreignKeys.map(fk => fk.name)).toEqual(["fk_vc_breeds_species"]);
    expect(ds.getMetadata(SpeciesEntity).uniques.map(unique => unique.name)).toEqual(["uq_vc_species_name"]);
    expect(ds.getMetadata(ReservationEntity).foreignKeys.map(fk => fk.name).sort()).toEqual([
      "fk_vc_reservations_animal", "fk_vc_reservations_client", "fk_vc_reservations_employee",
    ]);
  });
});
