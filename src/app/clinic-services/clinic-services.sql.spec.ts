import { join } from "path";
import { DataSource, In, SelectQueryBuilder } from "typeorm";
import { Actor } from "../core/authorization";
import { ReservationStatus } from "../core/enums/reservation-status.enum";
import { PersistenceService } from "../core/persistence/persistence.service";
import { ReservationEntity } from "../reservation/entities/reservation.entity";
import { findOpenReservations } from "../reservation/open-reservations";
import { ReservationBusinessService } from "../reservation/reservation.business.service";
import { isQualifiedForService } from "./clinic-service.projection";
import { ClinicServiceEntity } from "./entities/clinic-service.entity";
import { EmployeeServiceEntity } from "./entities/employee-service.entity";

const actor = (flags: Partial<Actor>): Actor => ({ id: "U-1", roleIds: [], isAdmin: false, isEmployee: false, isClient: false, employeeId: null, ...flags });

/**
 * Real TypeORM metadata (no database connection): names of migration 1795608000000 and the SQL generated for the new
 * columns and tables, so a mapping mistake (property name instead of column, a writable service_id, a composite
 * relation sharing a column) fails here instead of in SQL Server.
 */
describe("Clinic services SQL generated by TypeORM metadata", () => {
  let ds: DataSource;
  const flat = (sql: string) => sql.replace(/\s+/g, " ");

  beforeAll(async () => {
    ds = new DataSource({ type: "mssql", entities: [join(__dirname, "../../**/*.entity{.ts,.js}")] });
    await (ds as unknown as { buildMetadatas(): Promise<void> }).buildMetadatas();
  }, 30_000);
  afterEach(() => jest.restoreAllMocks());

  it("declares the names of migration 1795608000000 on vc_services, vc_employee_services and vc_reservations", () => {
    const services = ds.getMetadata(ClinicServiceEntity);
    expect(services.tableName).toBe("vc_services");
    expect(services.uniques.map(unique => `${unique.name}:${unique.columns.map(column => column.databaseName)}`)).toEqual(["uq_vc_services_code:code"]);
    expect(services.checks.map(check => check.name).sort()).toEqual(["ck_vc_services_code", "ck_vc_services_duration"]);
    expect(services.checks.find(check => check.name === "ck_vc_services_duration")?.expression).toBe("[duration_minutes] BETWEEN 1 AND 1440 AND [duration_minutes] % 5 = 0");
    expect(services.findColumnWithPropertyName("durationMinutes")).toMatchObject({ databaseName: "duration_minutes", type: "int", isNullable: false });
    expect(services.columns.map(column => column.databaseName)).not.toContain("price");

    const qualifications = ds.getMetadata(EmployeeServiceEntity);
    expect(qualifications.tableName).toBe("vc_employee_services");
    expect(qualifications.primaryColumns.map(column => column.databaseName)).toEqual(["employee_id", "service_id"]);
    expect(qualifications.foreignKeys.map(fk => `${fk.name}:${fk.columnNames}:${fk.referencedTablePath}:${fk.onDelete}`).sort()).toEqual([
      "fk_vc_employee_services_employee:employee_id:vc_employees:NO ACTION", "fk_vc_employee_services_service:service_id:vc_services:NO ACTION",
    ]);
    expect(qualifications.indices.map(index => `${index.name}:${index.columns.map(column => column.databaseName)}`)).toEqual(["ix_vc_employee_services_service_id:service_id"]);

    const reservations = ds.getMetadata(ReservationEntity);
    expect(reservations.foreignKeys.find(fk => fk.name === "fk_vc_reservations_service")).toMatchObject({ onDelete: "NO ACTION", referencedTablePath: "vc_services", columnNames: ["service_id"] });
    expect(reservations.indices.find(index => index.name === "ix_vc_reservations_service_id")?.columns.map(column => column.databaseName)).toEqual(["service_id"]);
    expect(reservations.findColumnWithPropertyName("serviceId")).toMatchObject({ databaseName: "service_id", isNullable: true, isUpdate: false, type: "uuid" });
    // Single-column relations only: no composite relation shares a column.
    for (const metadata of [reservations, qualifications]) expect(metadata.relations.every(relation => relation.joinColumns.length <= 1)).toBe(true);
    expect(reservations.relations.filter(relation => relation.joinColumns.some(column => column.databaseName === "service_id")).map(relation => relation.propertyName)).toEqual(["service"]);
  });

  it("never writes service_id in an UPDATE (the service of a reservation is immutable)", () => {
    const [update] = ds.createQueryBuilder().update(ReservationEntity)
      .set({ status: ReservationStatus.PENDING, serviceId: "OTHER" } as any).where({ id: "R-1" }).getQueryAndParameters();
    const assigned = [...flat(update).split(" WHERE ")[0].matchAll(/"([a-zA-Z_]+)" = /g)].map(match => match[1]);
    expect(assigned).toContain("status");
    expect(assigned).not.toContain("service_id");
    expect(assigned).not.toContain("serviceId");
  });

  it("joins the service by service_id in GET /reservations and loads it in GET /reservations/:id", async () => {
    const queries: string[] = [];
    jest.spyOn(SelectQueryBuilder.prototype, "getMany").mockImplementation(function (this: SelectQueryBuilder<any>) {
      queries.push(flat(this.getQuery()));
      return Promise.resolve([]);
    });
    const service = new ReservationBusinessService(new PersistenceService(), {} as any, {} as any, {} as any, {} as any, {} as any,
      ds.getRepository(ReservationEntity), {} as any, {} as any, {} as any);
    await service.list({ skip: 0, take: 10 } as any, actor({ isAdmin: true }));
    expect(queries[0]).toContain(`LEFT JOIN "vc_services" "service" ON "service"."id"="reservation"."service_id"`);
    expect(queries[0]).toContain(`"service"."duration_minutes" AS "service_duration_minutes"`);
    expect(queries[0]).not.toMatch(/"(serviceId|durationMinutes)"/);
  });

  it("selects service_id in the open-reservation read used by PUT /employees/:id/services", async () => {
    const queries: string[] = [];
    jest.spyOn(SelectQueryBuilder.prototype, "getMany").mockImplementation(function (this: SelectQueryBuilder<any>) {
      queries.push(flat(this.getQuery()));
      return Promise.resolve([]);
    });
    await findOpenReservations(ds.manager, { employeeId: "E-1" });
    expect(queries[0]).toContain(`"r"."service_id" AS "r_service_id"`);
    expect(queries[0]).toContain(`WHERE "r"."employee_id" = :value`);
  });

  it("checks a qualification by employee_id and service_id (plain read, no lock hint)", async () => {
    const queries: string[] = [];
    jest.spyOn(SelectQueryBuilder.prototype, "getCount").mockImplementation(function (this: SelectQueryBuilder<any>) {
      queries.push(flat(this.getQuery()));
      return Promise.resolve(1);
    });
    await expect(isQualifiedForService(ds.manager, "E-1", "S-1")).resolves.toBe(true);
    expect(queries[0]).toMatch(/FROM "vc_employee_services" "EmployeeServiceEntity"/);
    expect(queries[0]).toContain(`WHERE (("EmployeeServiceEntity"."employee_id" = :orm_param_0) AND ("EmployeeServiceEntity"."service_id" = :orm_param_1))`);
    expect(queries[0]).not.toMatch(/WITH \(|employeeId|serviceId/);
  });

  it("reads the service of a new reservation with a shared lock held until commit (HOLDLOCK, ROWLOCK)", async () => {
    const queries: string[] = [];
    jest.spyOn(SelectQueryBuilder.prototype, "getOne").mockImplementation(function (this: SelectQueryBuilder<any>) {
      queries.push(flat(this.getQuery()));
      return Promise.resolve(null);
    });
    await ds.manager.findOne(ClinicServiceEntity, { where: { id: "S-1" }, lock: { mode: "pessimistic_read" } });
    expect(queries[0]).toContain(`FROM "vc_services" "ClinicServiceEntity" WITH (HOLDLOCK, ROWLOCK)`);
  });

  it("counts references by service_id before deleting a service, and deletes removed qualifications by both key columns", async () => {
    const counts: string[] = [];
    jest.spyOn(SelectQueryBuilder.prototype, "getCount").mockImplementation(function (this: SelectQueryBuilder<any>) {
      counts.push(flat(this.getQuery()));
      return Promise.resolve(0);
    });
    await ds.manager.count(ReservationEntity, { where: { serviceId: "S-1" } });
    expect(counts[0]).toContain(`WHERE (("ReservationEntity"."service_id" = :orm_param_0))`);
    const [remove] = ds.createQueryBuilder().delete().from(EmployeeServiceEntity)
      .where({ employeeId: "E-1", serviceId: In(["S-1", "S-2"]) }).getQueryAndParameters();
    expect(flat(remove)).toMatch(/DELETE FROM "vc_employee_services" WHERE .*"employee_id" = @0.*"service_id" IN \(@1, @2\)/);
  });
});
