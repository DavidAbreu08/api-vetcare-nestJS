import { join } from "path";
import { DataSource, SelectQueryBuilder } from "typeorm";
import { AnimalEntity } from "../animal/entities/animal.entity";
import { Actor } from "../core/authorization";
import { ReservationStatus } from "../core/enums/reservation-status.enum";
import { PersistenceService } from "../core/persistence/persistence.service";
import { ReservationHistoryEntity } from "../reservation-history/entities/reservation-history.entity";
import { ReservationHistoryAction } from "../reservation-history/enums/reservation-history-action.enum";
import { UsersEntity } from "../users/entities/users.entity";
import { ReservationEntity } from "./entities/reservation.entity";
import { ClinicServiceEntity } from "../clinic-services/entities/clinic-service.entity";
import { ReservationBusinessService } from "./reservation.business.service";

const actor = (flags: Partial<Actor>): Actor => ({ id: "U-1", roleIds: [], isAdmin: false, isEmployee: false, isClient: false, employeeId: null, ...flags });

/**
 * Real TypeORM metadata (no database connection): the SQL generated for vc_reservations.created_by (migration
 * 1795521600000), so a mapping mistake (property name instead of column, a writable author) fails here instead of in
 * SQL Server.
 */
describe("Reservation authorship SQL generated by TypeORM metadata", () => {
  let ds: DataSource;
  const flat = (sql: string) => sql.replace(/\s+/g, " ");

  beforeAll(async () => {
    ds = new DataSource({ type: "mssql", entities: [join(__dirname, "../../**/*.entity{.ts,.js}")] });
    await (ds as unknown as { buildMetadatas(): Promise<void> }).buildMetadatas();
  }, 30_000);
  afterEach(() => jest.restoreAllMocks());

  it("declares the names of migration 1795521600000 (FK, index, filtered unique CREATED index)", () => {
    const reservations = ds.getMetadata(ReservationEntity);
    expect(reservations.foreignKeys.map(fk => `${fk.name}:${fk.columnNames}`)).toContain("fk_vc_reservations_created_by:created_by");
    expect(reservations.foreignKeys.find(fk => fk.name === "fk_vc_reservations_created_by")).toMatchObject({ onDelete: "NO ACTION", referencedTablePath: "vc_users" });
    const index = reservations.indices.find(candidate => candidate.name === "ix_vc_reservations_created_by");
    expect(index?.columns.map(column => column.databaseName)).toEqual(["created_by"]);
    const column = reservations.findColumnWithPropertyName("createdBy")!;
    expect(column).toMatchObject({ databaseName: "created_by", isNullable: true, isUpdate: false, type: "uuid" });
    // A single join column; no composite relation shares created_by.
    expect(reservations.relations.filter(relation => relation.joinColumns.some(join => join.databaseName === "created_by")).map(relation => relation.propertyName)).toEqual(["creator"]);
    expect(reservations.relations.every(relation => relation.joinColumns.length <= 1)).toBe(true);

    const history = ds.getMetadata(ReservationHistoryEntity);
    const created = history.indices.find(candidate => candidate.name === "uq_vc_reservation_history_created");
    expect(created).toMatchObject({ isUnique: true, where: "[action] = N'CREATED'" });
    expect(created?.columns.map(candidate => candidate.databaseName)).toEqual(["reservation_id"]);
  });

  it("inserts created_by = the actor from POST /reservations (staff booking for another client), with CREATED.changedBy = actor", async () => {
    const inserts: [string, unknown[]][] = [];
    const events: any[] = [];
    const manager: any = {
      // Connection of the open transaction: withLockTimeout sends its SET LOCK_TIMEOUT batches here.
      queryRunner: { isTransactionActive: true, databaseConnection: { request: () => ({ batch: jest.fn(async () => undefined) }) } },
      findOne: jest.fn(async (entity: unknown, { where }: any) => {
        if (entity === AnimalEntity) return { id: where.id };
        if (entity === UsersEntity) return { id: where.id, isActive: true };
        if (entity === ClinicServiceEntity) return { id: where.id, isActive: true, durationMinutes: 30 };
        return null;
      }),
      find: jest.fn(async () => []),
      // Real query builders (global block check of a booking without employee); getCount is stubbed below.
      createQueryBuilder: (entity: any, alias: string) => ds.createQueryBuilder(entity, alias),
      create: (entity: any, row: any) => ds.manager.create(entity, row),
      save: jest.fn(async (row: ReservationEntity) => {
        inserts.push(ds.createQueryBuilder().insert().into(ReservationEntity).values(row).getQueryAndParameters() as [string, unknown[]]);
        return { ...row, id: "R-1" };
      }),
    };
    const blockQueries: string[] = [];
    jest.spyOn(SelectQueryBuilder.prototype, "getCount").mockImplementation(function (this: SelectQueryBuilder<any>) {
      blockQueries.push(flat(this.getQuery()));
      return Promise.resolve(0);
    });
    const staff = actor({ id: "STAFF", isEmployee: true, employeeId: "E-1" });
    const business = new ReservationBusinessService(new PersistenceService(),
      { transaction: (work: (m: unknown) => unknown) => work(manager) } as any, {} as any, {} as any,
      { hasSystemRole: async () => true } as any, { record: async (_m: unknown, event: unknown) => { events.push(event); } } as any,
      { findOne: async () => null } as any,
      { findOne: async ({ where }: any) => ({ id: where.id, isActive: true, email: `${where.id}@x.pt`, name: where.id }) } as any,
      { findOne: async ({ where }: any) => ({ id: where.id }) } as any,
      { isActiveTutor: async () => true } as any);
    // respond() reloads the committed row; the double has none (404), the INSERT is what this test inspects.
    await expect(business.create({ animalId: "A-1", ownerId: "CLIENT", serviceId: "SVC", startAt: "2030-01-07T10:00:00Z" } as any, staff)).rejects.toBeDefined();

    // Without an employee only clinic-wide closures are checked (no applock).
    expect(blockQueries).toEqual([expect.stringContaining(`FROM "vc_blocked_times" "block" WHERE "block"."start_at" < :endAt AND "block"."end_at" > :startAt AND "block"."employee_id" IS NULL`)]);
    const [insert, params] = inserts[0];
    const [, columnList, valueList] = /^INSERT INTO "vc_reservations"\((.*?)\)(?: OUTPUT .*?)? VALUES \((.*)\)$/.exec(flat(insert)) ?? [];
    const columns = columnList.split(", ").map(column => column.slice(1, -1));
    for (const column of ["animal_id", "client_id", "created_by", "service_id", "employee_id", "start_at", "end_at", "status"]) {
      expect(columns.filter(name => name === column)).toHaveLength(1);
    }
    expect(columns.join(",")).not.toMatch(/[A-Z]/);
    // Resolve each column's placeholder (@n) to its typed parameter; DEFAULT columns have none.
    const placeholders = valueList.split(", ");
    const param = (column: string) => params[Number(placeholders[columns.indexOf(column)].slice(1))] as { value: unknown; type: string };
    expect(param("created_by")).toMatchObject({ value: "STAFF", type: "uniqueidentifier" });
    expect(param("client_id")).toMatchObject({ value: "CLIENT", type: "uniqueidentifier" });
    // Service of the new reservation (migration 1795608000000) and the server-computed end (startAt + 30 min).
    expect(param("service_id")).toMatchObject({ value: "SVC", type: "uniqueidentifier" });
    expect((param("end_at").value as Date).toISOString()).toBe("2030-01-07T10:30:00.000Z");
    expect(events[0].newData).toMatchObject({ serviceId: "SVC", endAt: "2030-01-07T10:30:00.000Z" });
    expect(events[0]).toMatchObject({ action: ReservationHistoryAction.CREATED, changedBy: "STAFF" });
    expect(events[0].newData).not.toHaveProperty("createdBy");
  });

  it("never writes created_by in an UPDATE, even when a caller passes it", () => {
    const [update] = ds.createQueryBuilder().update(ReservationEntity)
      .set({ status: ReservationStatus.CANCELLED, createdBy: "OTHER" } as any).where({ id: "R-1" }).getQueryAndParameters();
    const assigned = [...flat(update).split(" WHERE ")[0].matchAll(/"([a-zA-Z_]+)" = /g)].map(match => match[1]);
    expect(assigned).toEqual(expect.arrayContaining(["status", "updated_at"]));
    expect(assigned).not.toContain("created_by");
    expect(assigned).not.toContain("createdBy");
  });

  it("filters GET /reservations by created_by inside the caller's scope", async () => {
    const queries: string[] = [];
    jest.spyOn(SelectQueryBuilder.prototype, "getMany").mockImplementation(function (this: SelectQueryBuilder<any>) {
      queries.push(flat(this.getQuery()));
      return Promise.resolve([]);
    });
    const service = new ReservationBusinessService(new PersistenceService(), {} as any, {} as any, {} as any, {} as any, {} as any,
      ds.getRepository(ReservationEntity), {} as any, {} as any, {} as any);
    await service.list({ skip: 0, take: 10, createdBy: "U-1" } as any, actor({ isClient: true }));
    expect(queries[0]).toMatch(/WHERE \("reservation"\."client_id" = :actorId OR EXISTS .*\) AND "reservation"\."created_by" = :createdBy/);
    expect(queries[0]).not.toContain(`"creator"`);
    await service.list({ skip: 0, take: 10, createdBy: "U-9" } as any, actor({ isAdmin: true }));
    expect(queries[1]).toContain(`WHERE "reservation"."created_by" = :createdBy`);
  });
});
